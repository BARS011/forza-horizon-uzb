export class SettingsManager {
  constructor(storage, soundManager, renderer) {
    this.storage = storage;
    this.soundManager = soundManager;
    this.renderer = renderer;

    this.settings = this.storage.getSettings();
    this.currentLang = this.settings.language || "uz";

    this.fps = 60;
    this.frameCount = 0;
    this.lastFpsUpdate = performance.now();
    this.targetFps = this.settings.fpsLimit || 60;
    this.minFrameInterval = this.targetFps > 0 ? 1000 / this.targetFps : 0;
    this.lastFrameTime = performance.now();
  }

  applyGraphicsSettings(renderer, scene, camera) {
    if (!renderer) return;
    const preset = this.settings.graphics || "ultra";

    if (preset === "ultra") {
      renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.75));
      renderer.shadowMap.enabled = true;
      renderer.shadowMap.type = 2; // PCFSoftShadowMap
      if (camera) camera.far = 1400;
    } else if (preset === "super") {
      renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.25));
      renderer.shadowMap.enabled = true;
      renderer.shadowMap.type = 1;
      if (camera) camera.far = 1000;
    } else if (preset === "medium") {
      renderer.setPixelRatio(1.0);
      renderer.shadowMap.enabled = true;
      renderer.shadowMap.type = 0;
      if (camera) camera.far = 700;
    } else {
      renderer.setPixelRatio(0.85);
      renderer.shadowMap.enabled = false;
      if (camera) camera.far = 450;
    }

    if (camera) camera.updateProjectionMatrix();
  }

  setFpsLimit(fps) {
    this.targetFps = parseInt(fps, 10);
    this.minFrameInterval = this.targetFps > 0 ? 1000 / this.targetFps : 0;
    this.settings.fpsLimit = this.targetFps;
    this.storage.updateSettings({ fpsLimit: this.targetFps });
  }

  shouldRenderFrame(now) {
    if (this.minFrameInterval === 0) return true;
    const elapsed = now - this.lastFrameTime;
    if (elapsed >= this.minFrameInterval - 1) {
      this.lastFrameTime = now - (elapsed % this.minFrameInterval);
      return true;
    }
    return false;
  }

  updateFpsCounter() {
    this.frameCount++;
    const now = performance.now();
    if (now - this.lastFpsUpdate >= 500) {
      this.fps = Math.round((this.frameCount * 1000) / (now - this.lastFpsUpdate));
      this.frameCount = 0;
      this.lastFpsUpdate = now;
    }
    return this.fps;
  }

  setLanguage(langCode) {
    if (TRANSLATIONS[langCode]) {
      this.currentLang = langCode;
      this.settings.language = langCode;
      this.storage.updateSettings({ language: langCode });
      this.translateDOM();
    }
  }

  getText(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.uz;
    return dict[key] || key;
  }

  translateDOM() {
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
      const key = el.getAttribute("data-i18n");
      const text = this.getText(key);
      if (text) {
        if (el.tagName === "INPUT" && el.getAttribute("placeholder")) {
          el.setAttribute("placeholder", text);
        } else {
          el.textContent = text;
        }
      }
    });
  }
}
